// Katalog dokumentów transportowych używanych przez silnik doboru (documentEngine.js).
// Klucze (np. "44_India_Import") to stabilne identyfikatory używane w logice silnika —
// NIE są tożsame z numerem pliku PDF. `path` wskazuje fizyczny plik w public/templates/.
//
// path:      ścieżka w public/templates/ (null = plik jeszcze nie wgrany)
// available: czy PDF fizycznie istnieje i można go pobrać
//
// UWAGA — rozjazd numeracji: numer w kluczu katalogu bywa inny niż numer pliku PDF
// (pliki nadano wg innej kolejności). Dlatego `path` mapujemy wg ZNACZENIA (kraju),
// a nie wg prefiksu klucza. Np. "44_India_Import" → plik 22 (Bill of Entry India).
//
// --- METADANE DOBORU (ETAP 1) -----------------------------------------------
// transportModes:    galezie transportu, w ktorych dokument ma sens
//                    ('road' | 'sea' | 'air' | 'rail' | 'multimodal')
// issuerType:        kto FAKTYCZNIE wystawia dokument (slownik nizej)
// outputMode:        co platforma potrafi z nim zrobic
//   'final'      - dokument gotowy do uzycia w obrocie
//   'draft'      - wypelniona wersja robocza / wniosek; PDF musi dostac naglowek
//                  "WERSJA ROBOCZA - do zlozenia w: {authority}"
//   'blank_only' - platforma NIE wypelnia danymi uzytkownika; tylko pusty szablon
//                  plus informacja, kto go wystawia
// legalBasis:        podstawa prawna. `null` = NIE USTALONA (nie zgadujemy);
//                    lista 71 wpisow w docs/legalbasis_do_uzupelnienia.md
// authority:         organ lub podmiot wystawiajacy. UWAGA: to tekst RENDEROWANY
//                    uzytkownikowi (tresc naglowka dla 'draft'), wiec ma polskie
//                    znaki - inaczej niz komentarze, ktore zostaja w ASCII.
// validFrom/validTo: okno obowiazywania (ISO 'YYYY-MM-DD'). `validFrom` w przyszlosci
//                    => dokument NIE trafia do `required`, tylko do ostrzezen.
//                    Mechanizm sterowany katalogiem, nie kodem silnika.
// blockingIfMissing: brak dokumentu zatrzymuje przesylke (true) czy tylko utrudnia (false)
// category:          grupa z TEMPLATE_CATALOG (ue | transport | swiadectwo |
//                    celne_export | celne_import | towary_niebezp | inne | finansowe)
//
// Domyslny outputMode wynika z issuerType; odstepstwa maja komentarz przy polu:
//   shipper -> final            forwarder -> final          carrier -> draft
//   customs_authority -> draft  chamber_of_commerce -> draft
//   government_agency | bank | insurer | lab_or_inspector | notified_body |
